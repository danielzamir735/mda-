function buildTodayTopicsSection(todayTopics: string[]): string {
  return todayTopics.length > 0
    ? `\nנושאים שכבר נבחרו היום ברובריקות אחרות — אסור בהחלט לחזור עליהם, חובה לבחור נושא שונה לחלוטין: ${todayTopics.join(', ')}.\n`
    : ''
}

