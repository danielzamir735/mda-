// One fact per day, walking the pool in order — a fact only repeats after the whole
// pool has been used. `offset` lets a second rubric take a different fact the same day.
function pickClinicalFact(level: 'bls' | 'als', dateStr: string, offset = 0): ClinicalFact {
  const [y, m, d] = dateStr.split('-').map(Number)
  const dayNumber = Math.floor(Date.UTC(y, m - 1, d) / 86_400_000)
  const pool = CLINICAL_FACTS[level]
  return pool[(dayNumber + offset) % pool.length]
}
